function productIllustration(name, mark, index) {
  const hues = ["#12c48b", "#22b8d1", "#c9f95c", "#7c5cff", "#f2b84b", "#f07f66"];
  const accent = hues[index % hues.length];
  const safeName = name.replace(/[&<>"']/g, (char) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" }[char]));
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 800" role="img" aria-label="${safeName}"><defs><radialGradient id="g"><stop stop-color="${accent}" stop-opacity=".5"/><stop offset="1" stop-color="#061c12"/></radialGradient></defs><rect width="800" height="800" rx="64" fill="url(#g)"/><circle cx="400" cy="400" r="250" fill="none" stroke="${accent}" stroke-opacity=".45" stroke-width="5"/><circle cx="400" cy="400" r="200" fill="#03110a" fill-opacity=".45"/><text x="400" y="455" text-anchor="middle" font-size="230">${mark}</text><path d="M120 630 Q400 720 680 630" fill="none" stroke="${accent}" stroke-opacity=".7" stroke-width="10" stroke-linecap="round"/><text x="400" y="710" text-anchor="middle" fill="#dff7ea" font-family="Arial, sans-serif" font-size="25" letter-spacing="3">ECO PRODUCT</text></svg>`;
  return `data:image/svg+xml;charset=UTF-8,${encodeURIComponent(svg)}`;
}

